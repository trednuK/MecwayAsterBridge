# Offline test of Scripts/section_step.py (Python 2.7 and 3): STEP parsing,
# units, planar face selection and the exact 2D boundary loops.
#
#   python tests/test_section_step.py
#   powershell -ExecutionPolicy Bypass -File TestFiles/Tools/run_ipy.ps1 \
#       -Script tests/test_section_step.py          (IronPython 2.7.9)
#
# The STEP files in tests/data/section_step/ were made with FreeCAD 1.1
# (extrusions, in mm); rect_hole_m/rect_hole_inch are copies of rect_hole
# with the unit context edited, misc_entities.step is hand-written and
# gaps.step was generated by a small script (faces with edge ends that do not
# meet, real 0.5 mm slots, a 5 mm gap; see its header).
# Optional: SECTION_STEP_PIPECLIP=<folder with Mecway's PipeClip.liml,
# clip.step and pipe.step> also checks the Mecway sample (preview triangles
# of the .liml as selected points).

from __future__ import print_function

import io
import math
import os
import shutil
import sys
import tempfile

_HERE = os.path.dirname(os.path.abspath(globals().get("__file__",
                                                     sys.argv[0])))
sys.path.insert(0, os.path.join(_HERE, "..", "Scripts"))
import section_step as ss  # noqa: E402

DATA = os.path.join(_HERE, "data", "section_step")
X = [1.0, 0.0, 0.0]
Y = [0.0, 1.0, 0.0]
Z = [0.0, 0.0, 1.0]
FINE = {"chord_rel": 1e-6, "max_angle_deg": 0.5}


def check(name, cond, info=""):
    print(("OK   " if cond else "FOUT ") + name +
          ("" if cond or not info else "  [{0}]".format(info)))
    if not cond:
        check.failed = True


check.failed = False


def f(name):
    return os.path.join(DATA, name)


def raises(fn, text):
    try:
        fn()
    except ValueError as e:
        return text in str(e)
    return False


def rel(a, b):
    return abs(a / b - 1.0)


# --- analytic areas (mm2) of the end faces ------------------------------
PI = math.pi
I_AREA = 2 * 100 * 10 + 180 * 6 + 4 * (1 - PI / 4) * 12 ** 2
CASES = [
    # file, extrusion length (mm), area (mm2), loops, default rel. tolerance
    ("rect_hole.step", 20.0, 6000 - PI * 15 ** 2, 2, 2e-4),
    ("i_section.step", 30.0, I_AREA, 1, 2e-4),
    ("tube.step", 50.0, PI * (30 ** 2 - 25 ** 2), 2, 5e-4),
    ("ellipse.step", 15.0, PI * 40 * 20, 1, 5e-4),
    # FreeCAD face.Area (polynomial + rational B-spline edges)
    ("bspline.step", 10.0, 3237.830547945245, 1, 2e-4),
    # two adjacent coplanar faces per end (L of two boxes; plate + disc)
    ("l_two_faces.step", 10.0, 2700.0, 1, 1e-12),
    ("plate_disc.step", 5.0, 4800.0, 1, 1e-12),
]

for name, h, area, nloops, rtol in CASES:
    path = f(name)
    for z, n in ((0.0, Z), (h * 1e-3, [0.0, 0.0, -1.0])):
        off = z * n[2]
        # selected points: a point inside every face on that plane
        model = ss.load(path)
        on_plane = []
        for face in model.faces():
            try:
                o, nn = model.plane(face)
            except ValueError:
                continue
            if abs(abs(nn[2]) - 1) < 1e-12 and abs(o[2] - z) < 1e-12:
                on_plane.append(face.id)
        loops = ss.face_loops_2d(path, on_plane, X, Y)
        a = ss.loops_area(loops) * 1e6
        check("{0} z={1}: {2} loop(s)".format(name, z, nloops),
              len(loops) == nloops, len(loops))
        check("{0} z={1}: area (3 deg) rel. {2:.1e}".format(
            name, z, rel(a, area)), rel(a, area) < rtol, a)
        fine = ss.loops_area(ss.face_loops_2d(path, on_plane, X, Y, **FINE))
        check("{0} z={1}: area (0.5 deg) to 1e-5".format(name, z),
              rel(fine * 1e6, area) < 1e-5, fine * 1e6)
        closed = all(lp[0] != lp[-1] and len(lp) >= 3 for lp in loops)
        check("{0} z={1}: last point not repeated".format(name, z), closed)
        # outer loop CCW, holes CW
        areas = sorted((ss._area2d(lp) for lp in loops), reverse=True)
        check("{0} z={1}: outer CCW, holes CW".format(name, z),
              areas[0] > 0 and all(x < 0 for x in areas[1:]), areas)
        if len(on_plane) > 1:
            check("{0} z={1}: {2} coplanar faces merged".format(
                name, z, len(on_plane)), len(loops) == 1)

# --- find_faces: right end face, normal sign, holes ---------------------
tube = f("tube.step")
p_ring = [0.0275, 0.0, 0.0]                  # between r=25 and R=30 mm
ids0 = ss.find_faces(tube, Z, 0.0, [p_ring], 1e-7)
ids1 = ss.find_faces(tube, Z, 0.05, [[0.0275, 0.0, 0.05]], 1e-7)
idsm = ss.find_faces(tube, [0.0, 0.0, -1.0], -0.05,
                     [[0.0, -0.0275, 0.05]], 1e-7)
check("tube: one face at z=0", len(ids0) == 1, ids0)
check("tube: other face at z=50 mm", len(ids1) == 1 and ids1 != ids0,
      (ids0, ids1))
check("tube: normal -z with offset -0.05 gives the same face",
      idsm == ids1, idsm)
check("tube: point in the hole -> ValueError",
      raises(lambda: ss.find_faces(tube, Z, 0.0, [[0.0, 0.0, 0.0]], 1e-7),
             "no planar STEP face"))
check("tube: offset without face -> ValueError",
      raises(lambda: ss.find_faces(tube, Z, 0.02, [[0.0275, 0, 0.02]],
                                   1e-7), "no planar STEP face"))
lt = f("l_two_faces.step")
both = ss.find_faces(lt, Z, 0.01, [[0.01, 0.01, 0.01], [0.07, 0.035, 0.01]],
                     1e-7)
one = ss.find_faces(lt, Z, 0.01, [[0.07, 0.035, 0.01]], 1e-7)
check("L: two points pick both top faces", len(both) == 2, both)
check("L: one point picks one face", len(one) == 1 and one[0] in both, one)
la = ss.face_loops_2d(lt, both, X, Y)
check("L: union is one loop of 2700 mm2",
      len(la) == 1 and rel(ss.loops_area(la) * 1e6, 2700.0) < 1e-12)
lo = ss.face_loops_2d(lt, one, X, Y)
check("L: single face 30x40 = 1200 mm2",
      rel(ss.loops_area(lo) * 1e6, 1200.0) < 1e-12, ss.loops_area(lo))
# in-plane axes: x = P.u, y = P.v
lv = ss.face_loops_2d(lt, one, Y, [-1.0, 0.0, 0.0])
xs = [p[0] for p in lv[0]]
ys = [p[1] for p in lv[0]]
check("L: u=y, v=-x gives x in [0, 0.04], y in [-0.08, -0.05]",
      abs(min(xs)) < 1e-12 and abs(max(xs) - 0.04) < 1e-12 and
      abs(min(ys) + 0.08) < 1e-12 and abs(max(ys) + 0.05) < 1e-12,
      (min(xs), max(xs), min(ys), max(ys)))

# --- units ----------------------------------------------------------------
for name, scale in (("rect_hole.step", 1e-3), ("rect_hole_m.step", 1.0),
                    ("rect_hole_inch.step", 0.0254)):
    m = ss.load(f(name))
    check("{0}: length unit {1} m".format(name, scale),
          rel(m.scale, scale) < 1e-12, m.scale)
    top = ss.find_faces(f(name), Z, 0.0, [[70 * scale, 30 * scale, 0.0]],
                        1e-9 * scale)
    a = ss.loops_area(ss.face_loops_2d(f(name), top, X, Y, **FINE))
    check("{0}: area scales with unit^2".format(name),
          rel(a, (6000 - PI * 225) * scale ** 2) < 1e-5, a)

# --- hand-written file: parser and other entity types --------------------
misc = f("misc_entities.step")
m = ss.load(misc)
check("misc: string with escaped quotes",
      m.ent(1).args()[0] == "origin; with 'quotes' and #99 = X;",
      m.ent(1).args()[0])
check("misc: centimetre unit", rel(m.scale, 0.01) < 1e-12, m.scale)
check("misc: complex entity parts", m.ent(102).has(
    "GLOBAL_UNIT_ASSIGNED_CONTEXT") and m.ent(102).has(
    "REPRESENTATION_CONTEXT"))
sq = ss.find_faces(misc, Z, 0.0, [[0.08, 0.02, 0.0], [0.05, 0.05, 0.0]],
                   1e-9)
check("misc: square face found (point in hole ignored)", sq == [80], sq)
lm = ss.face_loops_2d(misc, sq, X, Y, **FINE)
check("misc: POLYLINE/TRIMMED/SEAM + circle hole, 2 loops",
      len(lm) == 2, len(lm))
check("misc: area (100 - 4 pi) cm2",
      rel(ss.loops_area(lm), (100 - 4 * PI) * 1e-4) < 1e-5,
      ss.loops_area(lm))
check("misc: polyline corner (10, 0) cm kept",
      any(abs(p[0] - 0.1) < 1e-12 and abs(p[1]) < 1e-12 for p in lm[0] +
          lm[1]))
tri = ss.find_faces(misc, Z, 0.0, [[0.22, 0.02, 0.0]], 1e-9)
lt2 = ss.face_loops_2d(misc, tri, X, Y)
check("misc: POLY_LOOP triangle 50 cm2",
      tri == [95] and rel(ss.loops_area(lt2), 50e-4) < 1e-12, lt2)
check("misc: face_ids in file order", ss.face_ids(misc) == [80, 95])

# --- gaps in the boundary (gaps.step, generated, faces at z = 0, mm) -----
gp = f("gaps.step")
GA, GB, GC = ss.face_ids(gp)                 # gaps / real slots / 5 mm gap
info = {}
lg = ss.face_loops_2d(gp, [GA], X, Y, info=info)
gc = sorted(info.get("gaps_closed", []))
check("gaps: one closed loop, area 100 x 100 mm",
      len(lg) == 1 and rel(ss.loops_area(lg), 0.01) < 1e-9,
      ss.loops_area(lg))
check("gaps: two gaps reported", len(gc) == 2, gc)
check("gaps: 0.01 mm at (100, 0.005) mm",
      len(gc) == 2 and abs(gc[0][0] - 1e-5) < 1e-12 and
      abs(gc[0][1][0] - 0.1) < 1e-12 and abs(gc[0][1][1] - 5e-6) < 1e-12,
      gc)
check("gaps: 0.5 mm at (0, 0.25) mm",
      len(gc) == 2 and abs(gc[1][0] - 5e-4) < 1e-12 and
      abs(gc[1][1][0]) < 1e-12 and abs(gc[1][1][1] - 2.5e-4) < 1e-12, gc)
check("gaps: smaller gap_tol (0.1 mm) raises with the largest gap",
      raises(lambda: ss.face_loops_2d(gp, [GA], X, Y, gap_tol=1e-4),
             "not closed, largest gap 0.5 mm at (0, "))
info = {}
ls = ss.face_loops_2d(gp, [GB], X, Y, info=info)
check("slots: real 0.5 mm notch and slot are not closed",
      len(ls) == 2 and info["gaps_closed"] == [] and
      rel(ss.loops_area(ls), (10000 - 2 * 0.5 * 40) * 1e-6) < 1e-9,
      (len(ls), info, ss.loops_area(ls)))
check("slots: notch kept (8 points), slot is a hole",
      sorted(len(lp) for lp in ls) == [4, 8])
check("big gap: 5 mm > 2 % of the size raises",
      raises(lambda: ss.face_loops_2d(gp, [GC], X, Y),
             "not closed, largest gap 5 mm at (400, "))
info = {}
lb = ss.face_loops_2d(gp, [GC], X, Y, gap_tol=0.006, info=info)
check("big gap: closed with gap_tol 6 mm",
      rel(ss.loops_area(lb), 0.01) < 1e-9 and len(info["gaps_closed"]) == 1
      and abs(info["gaps_closed"][0][0] - 0.005) < 1e-12, info)
check("find_faces: defective face found, open face skipped",
      ss.find_faces(gp, Z, 0.0, [[0.05, 0.05, 0.0], [0.27, 0.02, 0.0]],
                    1e-9) == [GA, GB])
check("find_faces: only the open face -> ValueError naming the gap",
      raises(lambda: ss.find_faces(gp, Z, 0.0, [[0.45, 0.05, 0.0]], 1e-9),
             "largest gap 5 mm"))

# --- errors -----------------------------------------------------------------
check("file not found",
      raises(lambda: ss.face_ids(f("missing.step")), "not found"))
curved = [i for i in ss.face_ids(tube)
          if not ss.load(tube).ent(ss.load(tube).ent(i).args()[2])
          .has("PLANE")]
check("not a plane",
      raises(lambda: ss.face_loops_2d(tube, curved[:1], X, Y),
             "is not a plane (CYLINDRICAL_SURFACE)"))
tmp = tempfile.mkdtemp()
try:
    src = io.open(misc, "r", encoding="latin-1").read()
    bad = src.replace("#30 = POLYLINE('',(#10,#11,#12));",
                      "#30 = OFFSET_CURVE_3D('',#34,1.,.F.,#2);")
    p = os.path.join(tmp, "bad.step")
    out = io.open(p, "w", encoding="latin-1")
    out.write(bad)
    out.close()
    check("unsupported curve type is named",
          raises(lambda: ss.face_loops_2d(p, [80], X, Y),
                 "unsupported curve type OFFSET_CURVE_3D (#30)"))
finally:
    shutil.rmtree(tmp)

# --- optional: Mecway's PipeClip sample --------------------------------------
pc = os.environ.get("SECTION_STEP_PIPECLIP", "")
if pc:
    import xml.etree.ElementTree as ET
    root = ET.parse(os.path.join(pc, "PipeClip.liml")).getroot()
    for g in root.findall("geometry"):
        path = os.path.join(pc, g.get("filename"))
        ids = ss.face_ids(path)
        bys = {}
        for t in g.find("preview").findall("triangle"):
            c = [sum(float(t.get(a + str(i))) for i in range(3)) / 3.0
                 for a in "xyz"]
            bys.setdefault(int(t.get("surfaceid")), []).append(c)
        for sid, cs in sorted(bys.items()):
            face = ss.load(path).ent(ids[sid - 2])
            try:
                o, n = ss.load(path).plane(face)
            except ValueError:
                continue
            got = ss.find_faces(path, n, ss._dot(o, n), cs, 1e-7)
            check("PipeClip {0} surface {1}: face #{2}".format(
                g.get("filename"), sid, face.id), got == [face.id], got)
    pipe = os.path.join(pc, "pipe.step")
    for z in (0.0, 0.006):
        got = ss.find_faces(pipe, Z, z, [[-0.001, 0.017, z]], 1e-7)
        a = ss.loops_area(ss.face_loops_2d(pipe, got, X, Y, **FINE))
        check("PipeClip pipe end face z={0}: half annulus R6/r4 mm".format(z),
              rel(abs(a), PI * (36 - 16) / 2 * 1e-6) < 1e-5, a)
else:
    print("(PipeClip check skipped: SECTION_STEP_PIPECLIP not set)")

if check.failed:
    sys.exit(1)
print("All tests passed.")
