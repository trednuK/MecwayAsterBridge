# bridge_from_aster.py
# Responsibility: reads the Code-Aster .resu file (POST_RELEVE_T
# table format) and injects the results into the active Mecway solution
# via solution.set_variable().
#
# Architecture:
#   - RESULT_FIELD_SPECS is the central registry of all supported
#     result fields. Per analysis CONFIG_BRIDGE["analyses"][...]
#     ["fields"] selects a subset of it (also the list on the start screen).
#   - STRUCT_FIELD_SPECS contains the extra tables for shells and beams.
#     They are loaded automatically when their 'parent' field is active
#     (e.g. 'vonmises') and therefore need no entry of their own in "fields".
#   - Adding a new field: entry in RESULT_FIELD_SPECS + make sure the
#     corresponding POST_RELEVE_T table is generated by bridge_to_aster.py
#     with the same INTITULE (_result_tables).
#
# Important (Mecway API, solution.set_variable): the list of values must be
# exactly as long as the number of nodes in the SOLUTION. The solution is
# the mesh of the last Mecway solve. If the model has changed since, not
# every Code-Aster node fits in the solution. main() therefore calls
# check_solution_mesh() before the Code-Aster run; AsterToMecway_results()
# also reports rows for nodes outside the solution.
#
# Compatible with IronPython 2.7.9.

import os
from collections import OrderedDict

from bridge_utils import (log, get_active_analysis, CONFIG_BRIDGE, tr,
                          run_name)


# POST_RELEVE_T reads INTITULE into a character(len=16) (rvtecn.F90 et al.,
# code_aster v17.4.0): longer names appear truncated in the .resu.
